"""Put the demo students' portraits into the demo images.

  python demo/apply_faces.py

Portraits in demo/avatars-src/ are samples from the SFHQ synthetic face set (CC0-1.0 on Kaggle), generated by StyleGAN2, so
they depict nobody. This script writes them as the people avatars and pastes each one,
as a round crop, at every face box listed in data/photos.json (web and thumb sizes). Safe to run twice.
"""
from pathlib import Path
import json

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parent
SRC = ROOT / "avatars-src"


def round_crop(img, size):
    img = img.convert("RGB").resize((size, size), Image.LANCZOS)
    mask = Image.new("L", (size * 4, size * 4), 0)
    ImageDraw.Draw(mask).ellipse((0, 0, size * 4 - 1, size * 4 - 1), fill=255)
    return img, mask.resize((size, size), Image.LANCZOS)


def main():
    photos = json.loads((ROOT / "data/photos.json").read_text(encoding="utf-8"))
    people = json.loads((ROOT / "data/people.json").read_text(encoding="utf-8"))
    for p in people:
        src = SRC / f"{p['id']}.jpg"
        if p.get("avatar") and src.exists():
            Image.open(src).convert("RGB").resize((256, 256), Image.LANCZOS).save(ROOT / p["avatar"], quality=88)
    pasted = 0
    for ph in photos:
        for key in ("web", "thumb"):
            path = ROOT / ph[key]
            img = Image.open(path).convert("RGB")
            changed = False
            for face in ph.get("faces", []):
                src = SRC / f"{face.get('person')}.jpg"
                if not src.exists():
                    continue
                x, y, w, h = face["bbox"]
                side = max(2, round(max(w * img.width, h * img.height)))
                face_img, mask = round_crop(Image.open(src), side)
                cx, cy = (x + w / 2) * img.width, (y + h / 2) * img.height
                img.paste(face_img, (round(cx - side / 2), round(cy - side / 2)), mask)
                changed = True
                pasted += key == "web"
            if changed:
                img.save(path, quality=85)
            if key == "web":  # the grid shows this colour while the image loads, so keep it equal to the real average
                ph["color"] = "#%02x%02x%02x" % Image.open(path).convert("RGB").resize((1, 1), Image.Resampling.BOX).getpixel((0, 0))
    for ph in photos:  # the viewer only outlines faces that carry a match status
        for face in ph.get("faces", []):
            face.setdefault("status", "high")
            face.setdefault("score", 0.8)
    (ROOT / "data/photos.json").write_text(json.dumps(photos, ensure_ascii=False), encoding="utf-8")
    print(f"portraits pasted into web images: {pasted}")


if __name__ == "__main__":
    main()
